export function compileUnitProfile(params: {
  id: string;
  name: string;
  callsign: string;
  faction: 'StrikeRoster' | 'WardenDirective';
  berthIndices: number[];
  echelon: EchelonTier;
  chassis: ChassisType;
  doctrine: DoctrineRole;
  lockedHardpoints: string[];
  knownDirectives?: string[];
  gridX?: number;
  gridY?: number;
  xp?: number;
  penalties?: { fpr: number; eva: number; cog: number };
}): CompiledUnit {
  const ech = ECHELON_SPECS[params.echelon];
  const chs = CHASSIS_SPECS[params.chassis];
  const doc = DOCTRINE_SPECS[params.doctrine];

  const modules = params.lockedHardpoints
    .map((id) => HARDPOINT_MODULES.find((m) => m.id === id))
    .filter((m): m is HardpointModule => Boolean(m));

  const bonusPlating = modules.reduce((sum, m) => sum + (m.bonusPlating ?? 0), 0);
  const bonusResilience = modules.reduce((sum, m) => sum + (m.bonusResilience ?? 0), 0);
  const bonusSurge = modules.reduce((sum, m) => sum + (m.bonusSurge ?? 0), 0);
  const bonusMove = modules.reduce((sum, m) => sum + (m.bonusMove ?? 0), 0);
  const hasCarbine = modules.some((m) => m.grantsRanged8);
  const hasResonanceInit = modules.some((m) => m.id === 'hp-minor-resonance');

  const penalties = params.penalties ?? { fpr: 0, eva: 0, cog: 0 };

  const fpr = Math.max(0, ech.baseFpr + doc.fprDelta - penalties.fpr);
  const eva = Math.max(0, ech.baseEva + doc.evaDelta - penalties.eva);
  const cog = Math.max(1, ech.baseCog + doc.cogDelta + chs.cogDelta - penalties.cog);
  const mov = Math.max(2, 4 + chs.moveDelta + doc.moveDelta + bonusMove);

  let rangedRange = 0;
  if (doc.grantsRanged12) {
    rangedRange = hasCarbine ? 18 : 12;
  } else if (hasCarbine) {
    rangedRange = 8;
  } else if (doc.unlocksResonance || hasResonanceInit) {
    rangedRange = 12;
  }

  const maxSurge = ech.baseSurge + bonusSurge;
  const defaultDirectives =
    params.knownDirectives ??
    (doc.unlocksResonance || hasResonanceInit
      ? ['res-arc-jolt', 'res-bio-mend', 'res-chrono-haste']
      : []);

  return {
    id: params.id,
    name: params.name,
    callsign: params.callsign,
    faction: params.faction,
    berthIndices: params.berthIndices,
    echelon: params.echelon,
    chassis: params.chassis,
    doctrine: params.doctrine,
    lockedHardpoints: params.lockedHardpoints,
    unlockedTotalHardpoints: ech.startingHardpoints,
    knownDirectives: defaultDirectives,

    modelsMax: ech.unitCount,
    modelsCurrent: ech.unitCount,
    fpr,
    eva,
    cog,
    mov,
    maxIntegrityPerModel: ech.maxIntegrityPerModel,
    maxSurge,
    plating: chs.nativePlating + bonusPlating,
    resilience: chs.nativeResilience + bonusResilience,
    rangedRange,

    gridX: params.gridX ?? 2,
    gridY: params.gridY ?? 15,
    accumulatedDamage: 0,
    currentSurge: maxSurge,
    actionsRemaining: 2,
    standardActionUsed: false,
    movedThisTurn: false,
    chargedThisTurn: false,
    activatedThisRound: false,
    activationsRemainingThisRound: params.berthIndices.length,

    staggered: false,
    criticalTrauma: false,
    shaken: false,
    hidden: false,
    deflectorActive: false,
    targetLockActive: false,
    kineticRamActive: false,
    harmonicBonusDice: 0,
    subsystemRuptures: [],

    xp: params.xp ?? 0,
    penalties,
  };
}

